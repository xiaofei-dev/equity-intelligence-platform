CREATE TABLE analytics.daily_price_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    security_id BIGINT NOT NULL REFERENCES analytics.security (id),
    trading_date DATE NOT NULL,
    open_price NUMERIC(20, 6) NOT NULL,
    high_price NUMERIC(20, 6) NOT NULL,
    low_price NUMERIC(20, 6) NOT NULL,
    close_price NUMERIC(20, 6) NOT NULL,
    adjusted_close NUMERIC(20, 6),
    volume BIGINT NOT NULL,
    provider_id BIGINT NOT NULL REFERENCES analytics.data_provider (id),
    adjustment_mode VARCHAR(32) NOT NULL,
    source_timezone VARCHAR(64) NOT NULL,
    revision_number INTEGER NOT NULL DEFAULT 1,
    source_record_id UUID NOT NULL REFERENCES analytics.source_record (id),
    available_at TIMESTAMPTZ NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL,
    normalization_version VARCHAR(64) NOT NULL,
    quality_status VARCHAR(32) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_daily_price_observation_revision
        UNIQUE (security_id, trading_date, provider_id, adjustment_mode, revision_number),
    CONSTRAINT ck_daily_price_observation_prices
        CHECK (
            open_price >= 0 AND high_price >= 0 AND low_price >= 0
            AND close_price >= 0
            AND (adjusted_close IS NULL OR adjusted_close >= 0)
        ),
    CONSTRAINT ck_daily_price_observation_volume CHECK (volume >= 0),
    CONSTRAINT ck_daily_price_observation_range
        CHECK (
            high_price >= low_price
            AND high_price >= open_price
            AND high_price >= close_price
            AND low_price <= open_price
            AND low_price <= close_price
        ),
    CONSTRAINT ck_daily_price_observation_revision CHECK (revision_number > 0),
    CONSTRAINT ck_daily_price_observation_times CHECK (ingested_at >= available_at),
    CONSTRAINT ck_daily_price_observation_quality
        CHECK (quality_status IN ('VALIDATED', 'PROVISIONAL', 'REJECTED', 'NOT_VERIFIED'))
);

CREATE INDEX ix_daily_price_observation_security_date
    ON analytics.daily_price_observation
        (security_id, trading_date DESC, available_at DESC);
CREATE INDEX ix_daily_price_observation_date_mode
    ON analytics.daily_price_observation (trading_date, adjustment_mode);
CREATE INDEX ix_daily_price_observation_source
    ON analytics.daily_price_observation (source_record_id);

