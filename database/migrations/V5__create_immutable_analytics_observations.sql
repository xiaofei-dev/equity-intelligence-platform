    security_id BIGINT NOT NULL REFERENCES analytics.security (id),
    provider_id BIGINT NOT NULL REFERENCES analytics.data_provider (id),
    provider_action_id VARCHAR(255) NOT NULL,
    action_type VARCHAR(32) NOT NULL,
    effective_date DATE NOT NULL,
    ex_date DATE,
    record_date DATE,
    payment_date DATE,
    amount NUMERIC(24, 10),
    currency CHAR(3),
    split_from NUMERIC(24, 10),
    split_to NUMERIC(24, 10),
    new_symbol VARCHAR(32),
    final_return NUMERIC(24, 10),
    revision_number INTEGER NOT NULL DEFAULT 1,
    source_record_id UUID NOT NULL REFERENCES analytics.source_record (id),
    available_at TIMESTAMPTZ NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_corporate_action_revision
        UNIQUE (provider_id, provider_action_id, revision_number),
    CONSTRAINT ck_corporate_action_type
        CHECK (action_type IN (
            'DIVIDEND', 'SPLIT', 'SYMBOL_CHANGE', 'LISTING',
            'DELISTING', 'SPIN_OFF'
        )),
    CONSTRAINT ck_corporate_action_revision CHECK (revision_number > 0),
    CONSTRAINT ck_corporate_action_times CHECK (ingested_at >= available_at),
    CONSTRAINT ck_corporate_action_fields CHECK (
        (action_type <> 'DIVIDEND' OR (amount IS NOT NULL AND currency IS NOT NULL))
        AND (action_type <> 'SPLIT' OR (
            split_from IS NOT NULL AND split_from > 0
            AND split_to IS NOT NULL AND split_to > 0
        ))
        AND (action_type <> 'SYMBOL_CHANGE' OR new_symbol IS NOT NULL)
    )
);

