CREATE TABLE analytics.coverage_result (
    run_id UUID NOT NULL REFERENCES analytics.screening_run (id),
    security_id BIGINT NOT NULL REFERENCES analytics.security (id),
    coverage_state VARCHAR(64) NOT NULL,
    company_type VARCHAR(64) NOT NULL,
    size_cohort VARCHAR(16) NOT NULL,
    quality_score NUMERIC(9, 4),
    valuation_score NUMERIC(9, 4),
    error_code VARCHAR(64),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (run_id, security_id),
    CONSTRAINT ck_coverage_result_state
        CHECK (coverage_state IN (
            'QUANT_ELIGIBLE', 'QUANT_INELIGIBLE', 'INSUFFICIENT_DATA',
            'STALE', 'ANALYSIS_FAILED', 'SPECIALIZED_MODEL_REQUIRED'
        )),
    CONSTRAINT ck_coverage_result_company_type
        CHECK (company_type IN (
            'MATURE_OPERATING_COMPANY', 'FINANCIAL', 'REIT', 'RESOURCE',
            'BIOTECHNOLOGY', 'EMERGING_GROWTH', 'SPECIAL_SITUATION', 'BENCHMARK'
        )),
    CONSTRAINT ck_coverage_result_size_cohort
        CHECK (size_cohort IN ('SMALL', 'MID', 'LARGE', 'MEGA')),
    CONSTRAINT ck_coverage_result_scores
        CHECK (
            (quality_score IS NULL OR quality_score BETWEEN 0 AND 100)
            AND (valuation_score IS NULL OR valuation_score BETWEEN 0 AND 100)
            AND (
                coverage_state = 'QUANT_ELIGIBLE'
                OR (quality_score IS NULL AND valuation_score IS NULL)
            )
        ),
    CONSTRAINT ck_coverage_result_error
        CHECK (
            coverage_state = 'QUANT_ELIGIBLE'
            OR error_code IS NOT NULL
        )
);

CREATE INDEX ix_coverage_result_run_state
    ON analytics.coverage_result (run_id, coverage_state);
CREATE INDEX ix_coverage_result_security_run
    ON analytics.coverage_result (security_id, run_id);

CREATE TABLE analytics.coverage_reason (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL,
    security_id BIGINT NOT NULL,
    reason_type VARCHAR(32) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    detail TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (run_id, security_id)
        REFERENCES analytics.coverage_result (run_id, security_id),
    CONSTRAINT uq_coverage_reason
        UNIQUE (run_id, security_id, reason_type, reason_code),
    CONSTRAINT ck_coverage_reason_type
        CHECK (reason_type IN ('EXCLUSION', 'MISSING_DATA', 'RISK_FLAG')),
    CONSTRAINT ck_coverage_reason_order CHECK (display_order >= 0)
);

CREATE INDEX ix_coverage_reason_run_type
    ON analytics.coverage_reason (run_id, reason_type, reason_code);

CREATE TABLE analytics.factor_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL,
    security_id BIGINT NOT NULL,
    factor_code VARCHAR(128) NOT NULL,
    factor_version VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    raw_value NUMERIC(24, 10),
    winsorized_value NUMERIC(24, 10),
    normalized_score NUMERIC(9, 4),
    cohort_level VARCHAR(64),
    cohort_size INTEGER,
    reason TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (run_id, security_id)
        REFERENCES analytics.coverage_result (run_id, security_id),
    FOREIGN KEY (factor_code, factor_version)
        REFERENCES analytics.factor_definition (factor_code, version),
    CONSTRAINT uq_factor_result
        UNIQUE (run_id, security_id, factor_code, factor_version),
    CONSTRAINT ck_factor_result_status
        CHECK (status IN ('VALID', 'MISSING', 'INVALID', 'NOT_APPLICABLE')),
    CONSTRAINT ck_factor_result_values CHECK (
        (
            status = 'VALID'
            AND raw_value IS NOT NULL
            AND winsorized_value IS NOT NULL
            AND normalized_score BETWEEN 0 AND 100
            AND cohort_level IS NOT NULL
            AND cohort_size > 0
            AND reason IS NULL
        )
        OR (
            status <> 'VALID'
            AND raw_value IS NULL
            AND winsorized_value IS NULL
            AND normalized_score IS NULL
            AND reason IS NOT NULL
        )
    ),
    CONSTRAINT ck_factor_result_cohort
        CHECK (
            cohort_level IS NULL
            OR cohort_level IN (
                'SECTOR_SIZE_COMPANY_TYPE',
                'SECTOR_COMPANY_TYPE',
                'GENERAL_COMPANY'
            )
        )
);

CREATE INDEX ix_factor_result_run_factor_score
    ON analytics.factor_result (run_id, factor_code, normalized_score DESC);
CREATE INDEX ix_factor_result_run_security
    ON analytics.factor_result (run_id, security_id);

CREATE TABLE analytics.factor_result_lineage (
    factor_result_id BIGINT NOT NULL REFERENCES analytics.factor_result (id),
    source_record_id UUID NOT NULL REFERENCES analytics.source_record (id),
    lineage_role VARCHAR(64),
    PRIMARY KEY (factor_result_id, source_record_id)
);

CREATE INDEX ix_factor_result_lineage_source
    ON analytics.factor_result_lineage (source_record_id);

CREATE TABLE analytics.strategy_rating (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL,
    security_id BIGINT NOT NULL,
    strategy_version VARCHAR(128) NOT NULL
        REFERENCES analytics.strategy_definition (strategy_version),
    status VARCHAR(32) NOT NULL,
    score NUMERIC(9, 4),
    rank INTEGER,
    error_code VARCHAR(64),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (run_id, security_id)
        REFERENCES analytics.coverage_result (run_id, security_id),
    CONSTRAINT uq_strategy_rating
        UNIQUE (run_id, security_id, strategy_version),
    CONSTRAINT uq_strategy_rating_rank
        UNIQUE (run_id, strategy_version, rank),
    CONSTRAINT ck_strategy_rating_status
        CHECK (status IN (
            'SCORED', 'INSUFFICIENT_DATA', 'NOT_DEFINED', 'NOT_APPLICABLE'
        )),
    CONSTRAINT ck_strategy_rating_values CHECK (
        (
            status = 'SCORED'
            AND score BETWEEN 0 AND 100
            AND (rank IS NULL OR rank > 0)
            AND error_code IS NULL
        )
        OR (
            status <> 'SCORED'
            AND score IS NULL
            AND rank IS NULL
            AND (
                status IN ('NOT_DEFINED', 'NOT_APPLICABLE')
                OR error_code IS NOT NULL
            )
        )
    )
);

CREATE INDEX ix_strategy_rating_run_strategy_rank
    ON analytics.strategy_rating (run_id, strategy_version, rank);
CREATE INDEX ix_strategy_rating_security_strategy_run
    ON analytics.strategy_rating (security_id, strategy_version, run_id);

CREATE TABLE analytics.factor_contribution (
    strategy_rating_id BIGINT NOT NULL REFERENCES analytics.strategy_rating (id),
    factor_code VARCHAR(128) NOT NULL,
    normalized_score NUMERIC(9, 4) NOT NULL,
    weight NUMERIC(9, 6) NOT NULL,
    contribution NUMERIC(12, 6) NOT NULL,
    PRIMARY KEY (strategy_rating_id, factor_code),
    CONSTRAINT ck_factor_contribution_score
        CHECK (normalized_score BETWEEN 0 AND 100),
    CONSTRAINT ck_factor_contribution_weight
        CHECK (weight >= 0 AND weight <= 1)
);

CREATE INDEX ix_factor_contribution_factor
    ON analytics.factor_contribution (factor_code, strategy_rating_id);

CREATE TABLE analytics.horizon_assessment (
    run_id UUID NOT NULL,
    security_id BIGINT NOT NULL,
    horizon VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    score NUMERIC(9, 4),
    label VARCHAR(64) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (run_id, security_id, horizon),
    FOREIGN KEY (run_id, security_id)
        REFERENCES analytics.coverage_result (run_id, security_id),
    CONSTRAINT ck_horizon_assessment_horizon
        CHECK (horizon IN ('NEAR_TERM', 'MEDIUM_TERM', 'LONG_TERM')),
    CONSTRAINT ck_horizon_assessment_status
        CHECK (status IN (
            'SCORED', 'INSUFFICIENT_DATA', 'NOT_DEFINED', 'NOT_APPLICABLE'
        )),
    CONSTRAINT ck_horizon_assessment_score CHECK (
        (status = 'SCORED' AND (score IS NULL OR score BETWEEN 0 AND 100))
        OR (status <> 'SCORED' AND score IS NULL)
    ),
    CONSTRAINT ck_horizon_assessment_medium_term
        CHECK (
            horizon <> 'MEDIUM_TERM'
            OR (status = 'NOT_DEFINED' AND score IS NULL)
        )
);

CREATE INDEX ix_horizon_assessment_run
    ON analytics.horizon_assessment (run_id, horizon, status);

CREATE FUNCTION analytics.reject_completed_run_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    run_status VARCHAR(32);
BEGIN
    SELECT status INTO run_status
    FROM analytics.screening_run
    WHERE id = COALESCE(NEW.run_id, OLD.run_id);

    IF run_status IN ('SUCCEEDED', 'FAILED') THEN
        RAISE EXCEPTION 'Results of completed screening runs are immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_coverage_result_immutable
BEFORE INSERT OR UPDATE OR DELETE ON analytics.coverage_result
FOR EACH ROW EXECUTE FUNCTION analytics.reject_completed_run_change();
CREATE TRIGGER tr_coverage_reason_immutable
BEFORE INSERT OR UPDATE OR DELETE ON analytics.coverage_reason
FOR EACH ROW EXECUTE FUNCTION analytics.reject_completed_run_change();
CREATE TRIGGER tr_factor_result_immutable
BEFORE INSERT OR UPDATE OR DELETE ON analytics.factor_result
FOR EACH ROW EXECUTE FUNCTION analytics.reject_completed_run_change();
CREATE TRIGGER tr_strategy_rating_immutable
BEFORE INSERT OR UPDATE OR DELETE ON analytics.strategy_rating
FOR EACH ROW EXECUTE FUNCTION analytics.reject_completed_run_change();
CREATE TRIGGER tr_horizon_assessment_immutable
BEFORE INSERT OR UPDATE OR DELETE ON analytics.horizon_assessment
FOR EACH ROW EXECUTE FUNCTION analytics.reject_completed_run_change();

CREATE FUNCTION analytics.reject_completed_factor_child_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    run_status VARCHAR(32);
BEGIN
    SELECT run.status INTO run_status
    FROM analytics.factor_result result
    JOIN analytics.screening_run run ON run.id = result.run_id
    WHERE result.id = COALESCE(NEW.factor_result_id, OLD.factor_result_id);

    IF run_status IN ('SUCCEEDED', 'FAILED') THEN
        RAISE EXCEPTION 'Lineage of completed screening runs is immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_factor_result_lineage_immutable
BEFORE INSERT OR UPDATE OR DELETE ON analytics.factor_result_lineage
FOR EACH ROW EXECUTE FUNCTION analytics.reject_completed_factor_child_change();

